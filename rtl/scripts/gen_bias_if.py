"""Generate the neuron_ctrl <-> bias_b1 interface (rev E, for bias_b1 rev C).

Writes rtl/nc_bias_ports.vh (port declarations, included in the port list)
and rtl/nc_bias_if.vh (latches whose Q pin is the port itself, plus the ua[0]
master-mode lines). Port names and order come from the .subckt line of
cells/bias/bias_b1.spice, so they match it exactly.

Run from the repo root:  python3 rtl/scripts/gen_bias_if.py [--provisional]
  --provisional  use a placeholder rev C port list (until bias_b1.spice says
                 "REV C PORTS STABLE"); the real file is required otherwise.

Rules (docs/08 Updated Plan.md section 4, docs/regmap.md section 3.2):
  Current DACs  <p>_b0..b4 (fixed range, 5-bit code, 0 = off): the 5-bit codes
                are packed LSB first, in bias_b1 port order, into one 40-bit
                word at bytes A_IDAC..A_IDAC+4 (code k = word[5k+4:5k], b0 = LSB).
  Voltage DAC   <p>_c0..c5: byte A_VDAC [5:0] (c0 = LSB).
  bias_en = ANA[6], ib_x2 = MODE[3], ua0_* from UA0_MODE = MODE[1:0].
  Every code passes straight through (no decode); reset = all 0 = off.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
MASTER = ["ua0_s0", "ua0_s1", "ua0_stim", "ua0_int", "bias_en", "ib_x2"]
N_IDAC, IDAC_BITS, N_VDAC, VDAC_BITS = 8, 5, 1, 6

# placeholder = the bias_b1 rev C DRAFT port list (2026-11-19): 5 current DACs i0..i4,
# 3 voltage-path (resistor) DACs r0..r2, the vth_ref VDAC v0, master lines
PROVISIONAL = ([f"i{k}_b{j}" for k in range(5) for j in range(5)]
               + [f"r{k}_b{j}" for k in range(3) for j in range(5)] + [f"v0_c{j}" for j in range(6)] + MASTER)


def regmap_addr():
    src = open(os.path.join(ROOT, "rtl", "nc_regmap.vh")).read()
    a = {m.group(1): int(m.group(2), 16) for m in re.finditer(r"localparam\s+(A_\w+)\s*=\s*5'h([0-9A-Fa-f]+)", src)}
    return a["A_IDAC"], a["A_VDAC"], a["A_ANA"], a["A_MODE"]


def digital_ports(provisional):
    if provisional:
        return list(PROVISIONAL), "PROVISIONAL rev C port list (bias_b1.spice not yet stable)"
    spice = open(os.path.join(ROOT, "cells", "bias", "bias_b1.spice")).read()
    if "REV C PORTS STABLE" not in spice:
        sys.exit("cells/bias/bias_b1.spice is not marked 'REV C PORTS STABLE' (use --provisional)")
    m = re.search(r"^\.subckt\s+bias_b1\s+(.*(?:\n\+.*)*)$", spice, re.M)
    names = m.group(1).replace("\n+", " ").split()
    dig = [n for n in names if re.match(r"^\w+_[bc]\d$", n) or n in MASTER]
    return dig, "cells/bias/bias_b1.spice"


def main():
    prov = "--provisional" in sys.argv
    A_IDAC, A_VDAC, A_ANA, A_MODE = regmap_addr()
    ports, src = digital_ports(prov)
    assert [n for n in ports if n in MASTER] == MASTER, "master lines missing or out of order"
    # group code bits by DAC prefix, in order of first appearance
    groups = {}
    for n in ports:
        mm = re.match(r"^(\w+)_([bc])(\d)$", n)
        if mm:
            groups.setdefault((mm.group(1), mm.group(2)), []).append(int(mm.group(3)))
    idacs = [p for (p, t) in groups if t == "b"]
    vdacs = [p for (p, t) in groups if t == "c"]
    assert len(idacs) == N_IDAC and len(vdacs) == N_VDAC, (idacs, vdacs)
    for (p, t), bits in groups.items():
        w = IDAC_BITS if t == "b" else VDAC_BITS
        assert sorted(bits) == list(range(w)), f"{p}: bits {bits}"

    lat = []                                  # (port, byte, bit)
    for k, p in enumerate(idacs):
        for j in range(IDAC_BITS):
            pos = IDAC_BITS * k + j
            lat.append((f"{p}_b{j}", A_IDAC + pos // 8, pos % 8))
    for j in range(VDAC_BITS):
        lat.append((f"{vdacs[0]}_c{j}", A_VDAC, j))
    lat += [("bias_en", A_ANA, 6), ("ib_x2", A_MODE, 3)]
    dec = [
        f"    wire [1:0] ua0_m = regs[8*{A_MODE} +: 2];",
        "    assign ua0_s0   = (ua0_m == 2'd0) | (ua0_m == 2'd3);",
        "    assign ua0_s1   = (ua0_m == 2'd1);",
        "    assign ua0_stim = (ua0_m == 2'd2);",
        "    assign ua0_int  = ua0_m[1] & bias_en;",
    ]
    assert {n for n, _, _ in lat} | {"ua0_s0", "ua0_s1", "ua0_stim", "ua0_int"} == set(ports)

    hdr = (f"// GENERATED by rtl/scripts/gen_bias_if.py -- do not edit. Source: {src}.\n"
           f"// Current DACs (code k = 40-bit word at 0x{A_IDAC:02X}..0x{A_IDAC + 4:02X}, bits [5k+4:5k]): "
           + ", ".join(f"{k}={p}" for k, p in enumerate(idacs)) + f"; voltage DAC 0x{A_VDAC:02X}[5:0]: {vdacs[0]}\n")
    with open(os.path.join(ROOT, "rtl", "nc_bias_ports.vh"), "w", newline="\n") as f:
        f.write(hdr)
        f.write(f"// {len(ports)} bias_b1 control lines in bias_b1 port order (included inside the neuron_ctrl port list)\n")
        for n in ports:
            f.write(f"    output wire {n},\n")
    with open(os.path.join(ROOT, "rtl", "nc_bias_if.vh"), "w", newline="\n") as f:
        f.write(hdr)
        f.write("// Pass-through bits: one latch per bit with Q = the port net (no feed-through buffer).\n")
        f.write("// regs (byte image) mirrors them only in simulation.\n")
        for n, a, b in lat:
            f.write(f"    `NC_LAT(l_{n}, {n}, {a}, {b})\n")
        f.write("`ifndef SYNTHESIS\n")
        for n, a, b in lat:
            f.write(f"    assign regs[8*{a}+{b}] = {n};\n")
        f.write("`else\n")
        for n, a, b in lat:
            f.write(f"    assign regs[8*{a}+{b}] = 1'b0;\n")
        f.write("`endif\n")
        f.write("// ua[0] master-mode lines\n")
        f.write("\n".join(dec) + "\n")
    print(f"{src}: {len(ports)} ports, {len(lat)} latches; IDAC order {idacs}; VDAC {vdacs}")


if __name__ == "__main__":
    main()
