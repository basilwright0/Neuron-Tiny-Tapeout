"""Write the top-level LVS reference netlist work/top_ref.spice (plain Python).

Hierarchical: each block's LVS netlist (or an empty black-box .subckt for placeholders), the control macro's
gate-level netlist (from macros/neuron_ctrl/neuron_ctrl.spice) on the PDK std-cell SPICE, the std cells of
the top level, and the top subckt tt_um_basilwright0_analog_neurons wiring them per config.nets().
Usage: python3 netlist.py   (needs PDK_ROOT/PDK for the std-cell SPICE)
"""
import json, os, re
import config as C

fp = C.fp


def subckts(text):
    """{name: (ports, full text)} of a SPICE file (handles '+' continuations)."""
    lines = []
    for ln in text.splitlines():
        if ln.startswith("+") and lines:
            lines[-1] += " " + ln[1:].strip()
        else:
            lines.append(ln)
    out, cur, body = {}, None, []
    for ln in lines:
        t = ln.strip()
        if t.lower().startswith(".subckt"):
            w = t.split()
            cur = w[1]
            ports = [p for p in w[2:] if "=" not in p]
            body = [ln]
        elif cur:
            body.append(ln)
            if t.lower().startswith(".ends"):
                out[cur] = (ports, "\n".join(body))
                cur = None
    return out


def main():
    I = C.instances()
    nets = C.nets()
    conn = {}
    for n, lst in nets.items():
        for inst, pin in lst:
            conn[(inst, pin)] = n
    parts = ["* LVS reference for " + C.TOP + " (generated by layout/top/netlist.py; do not edit)"]
    defs = {}
    # ---- std cells: full PDK library (the macro uses many)
    pdk = os.environ["PDK_ROOT"] + "/" + os.environ["PDK"] + "/libs.ref/gf180mcu_fd_sc_mcu7t5v0/spice/gf180mcu_fd_sc_mcu7t5v0.spice"
    sc = subckts(open(pdk).read())
    # ---- macro: drop the black-box std-cell stubs, keep neuron_ctrl
    mac = subckts((C.ROOT / C.LIB["neuron_ctrl"]["lvs"]).read_text())
    defs["neuron_ctrl"] = mac["neuron_ctrl"]
    used_sc = set(re.findall(r"(gf180mcu_fd_sc_mcu7t5v0__\w+)", mac["neuron_ctrl"][1]))
    used_sc |= {C.SC + c for c in C.SC_W}
    for c in sorted(used_sc):
        parts.append(sc[c][1])
    # ---- blocks
    cells = {c for c, _, _ in I.values()}
    ports_of = {}
    for cell in sorted(cells):
        d = C.LIB[cell]
        if cell == "neuron_ctrl":
            parts.append(mac["neuron_ctrl"][1]); ports_of[cell] = mac["neuron_ctrl"][0]
            continue
        sub = d.get("sub", cell)
        txt = (C.ROOT / d["lvs"]).read_text()
        S = subckts(txt)
        if d["final"]:
            for name, (p, body) in S.items():
                if name not in defs:
                    defs[name] = (p, body); parts.append(body)
            ports_of[cell] = S[sub][0]
        else:
            # placeholder: black box whose ports are exactly the placeholder's labels
            g = json.loads((C.WORK / "geo" / f"{cell}.json").read_text())
            p = sorted(g["pins"])
            parts.append(f".subckt {sub} {' '.join(p)}\n* PLACEHOLDER (black box)\n.ends {sub}")
            ports_of[cell] = p
    # ---- top
    tpins = ([f"{io}[{i}]" for io in ("ui_in", "uo_out", "uio_in", "uio_out", "uio_oe") for i in range(8)]
             + [f"ua[{i}]" for i in range(8)] + ["ena", "clk", "rst_n", "VDPWR", "VGND"])
    body = [f".subckt {C.TOP} " + " ".join(tpins)]
    for inst, (cell, x, y) in sorted(I.items()):
        d = C.LIB[cell]
        sub = d.get("sub", cell)
        args = []
        for p in ports_of[cell]:
            if p in ("vdd", "VDD"):
                args.append("VDPWR")
            elif p in ("vss", "VSS"):
                args.append("VGND")
            elif (inst, p) in conn:
                args.append(conn[(inst, p)])
            elif inst == "d1" and p == "vsrcp":
                args.append("vsrc")
            elif inst == "r1" and p == "pad":
                args.append("ua[1]")
            else:
                args.append(f"nc_{inst}_{p}")
        body.append(f"X{inst} " + " ".join(args) + f" {sub}")
    for inst, (cell, x, y) in sorted(C.std_cells().items()):
        name = C.SC + cell
        args = []
        for p in sc[name][0]:
            if p in ("VDD", "VNW"):
                args.append("VDPWR")
            elif p in ("VSS", "VPW"):
                args.append("VGND")
            else:
                args.append(conn.get((inst, p), f"nc_{inst}_{p}"))
        body.append(f"X{inst} " + " ".join(args) + f" {name}")
    body.append(f".ends {C.TOP}")
    parts.append("\n".join(body))
    out = C.WORK / "top_ref.spice"
    out.write_text("\n\n".join(parts) + "\n")
    print("wrote", out, "-", len(I), "blocks,", len(C.std_cells()), "std cells")


if __name__ == "__main__":
    main()
