"""Write work/assemble.tcl: the magic script that builds the top cell (plain Python).

The script reads every block GDS read-only (so GDS output copies the blocks byte for byte), starts from the
TT template DEF (pins + PR boundary), draws the Metal4 power stripes as ports, places blocks and std cells,
paints fixed geometry (geom.py), pin stubs and routes (work/routes.json), then saves mag/<top>.mag, writes
gds/<top>.gds, lef/<top>.lef (pin-only) and the LVS extraction work/top_ext.spice.
Run from layout/top:  magic -dnull -noconsole -rcfile $PDK_ROOT/$PDK/libs.tech/magic/$PDK.magicrc work/assemble.tcl
"""
import json
import config as C
import geom as GM

fp = C.fp
VP = 0.19


def main():
    I = C.instances()
    F = GM.fixed()
    R = json.loads((C.WORK / "routes.json").read_text())
    root = C.ROOT
    T = ["# generated by layout/top/assemble.py -- do not edit", "drc off", "gds readonly true",
         "gds rescale false", "snap internal", "locking disable"]
    T.append(f"gds read {C.WORK}/gds/stdcells.gds")
    cells = sorted({c for c, _, _ in I.values()}, key=lambda c: c != "neuron_ctrl")
    for c in cells:
        T.append(f"gds read {C.WORK}/gds/{c}.gds")
    for c in cells:
        T.append(f"load {c}; catch {{port makeall}}")
    T += [f"def read {root}/mag/tt_analog_1x2.def", f"cellname rename tt_um_template {C.TOP}", f"load {C.TOP}",
          "tech unlock *"]
    # stripes as ports (init_project.tcl style)
    for net, layer, r, use in F.ports:
        T += [f"box values {r[0]}um {r[1]}um {r[2]}um {r[3]}um", f"paint {layer}",
              f"label {net} FreeSans 0.25u -{layer}", "port make", f"port use {use}", "port class bidirectional",
              "port connections n s e w"]
    # instances
    for inst, (cell, x, y) in sorted(I.items()):
        T += [f"box values {x:.3f}um {y:.3f}um {x:.3f}um {y:.3f}um", f"getcell {cell} child 0 0", f"identify {inst}"]
    for inst, cell, x, y in F.cells:
        T += [f"box values {x:.3f}um {y:.3f}um {x:.3f}um {y:.3f}um", f"getcell {cell} child 0 0", f"identify {inst}"]
    # geometry, grouped by layer (vias last)
    shapes = [(l, r, n) for l, r, n in F.shapes if not (l == "metal4" and any(r == p[2] for p in F.ports))]
    shapes += [(l, tuple(r), n) for l, r, n in R["_stubs"]]
    def cutgap(a, b):               # edge-to-edge distance of two 0.28 um via cuts
        gx = max(0.0, abs(a[0] - b[0]) - 0.28); gy = max(0.0, abs(a[1] - b[1]) - 0.28)
        return (gx * gx + gy * gy) ** 0.5
    pend_bridge = []
    fixed_vias, fv = [], []
    for idx, (l, r, n) in enumerate(list(shapes)):
        if l in ("via2", "via3"):
            c = ((r[0] + r[2]) / 2, (r[1] + r[3]) / 2)
            near = [q for k, q, nn in fixed_vias if k == l and nn == n and cutgap(q, c) < 0.27]
            if near:
                lo, hi = {"via2": ("metal2", "metal3"), "via3": ("metal3", "metal4")}[l]
                q = near[0]
                B = (round(min(c[0], q[0]) - 0.14, 3), round(min(c[1], q[1]) - 0.14, 3),
                     round(max(c[0], q[0]) + 0.14, 3), round(max(c[1], q[1]) + 0.14, 3))
                fv += [(lo, B, n), (hi, B, n)]
                shapes[idx] = None
                continue
            fixed_vias.append((l, c, n))
    shapes = [x for x in shapes if x is not None] + fv
    ndrop = 0
    for net, rec in R.items():
        if net.startswith("_"):
            continue
        wires = [(l, tuple(r)) for l, r in rec["wires"]]
        shapes += [(l, r, net) for l, r in wires]
        kept = [(k, c) for k, c, n in fixed_vias if n == net]
        vlist = []
        for kind, x, y in rec["vias"]:
            near = [c for k, c in kept if k == kind and (c[0], c[1]) != (x, y) and cutgap(c, (x, y)) < 0.27]
            if near:                       # cut spacing: keep the other via, bridge the pads on both metals
                cx, cy = near[0]
                lo, hi = {"via2": ("metal2", "metal3"), "via3": ("metal3", "metal4")}[kind]
                pend_bridge.append((lo, hi, (x, y), (cx, cy), net))
                ndrop += 1
                continue
            kept.append((kind, (x, y)))
            vlist.append((kind, x, y))
        for kind, x, y in vlist:
            lo, hi = {"via2": ("metal2", "metal3"), "via3": ("metal3", "metal4")}[kind]
            for lay in (lo, hi):
                # pad = the wire cross-section; extended 0.05 along the wire; 0.38 square if no wire (stack)
                on = [r for l, r in wires if l == lay and r[0] - 1e-6 <= x <= r[2] + 1e-6 and r[1] - 1e-6 <= y <= r[3] + 1e-6]
                hz = any(r[2] - r[0] > 0.3 for r in on); vt = any(r[3] - r[1] > 0.3 for r in on)
                hx = hy = 0.19          # 0.38 square (enclosure); steps against the wire are closed below
                # a same-net via pad on this layer diagonally closer than 0.28: narrow the pad across its wire
                # (0.28 across, 0.38 along: enclosure 0.01 / 0.06)
                for k2, x2, y2 in vlist:
                    if (x2, y2) == (x, y) or {k2, kind} - {"via2", "via3"} or lay not in (
                            {"via2": ("metal2", "metal3"), "via3": ("metal3", "metal4")}[k2]):
                        continue
                    gx = abs(x2 - x) - 0.38; gy = abs(y2 - y) - 0.38
                    if gx < 0 and gy < 0:
                        continue
                    if (max(gx, 0) ** 2 + max(gy, 0) ** 2) ** 0.5 < 0.28:
                        if hz and not vt:
                            hy = 0.14
                        elif vt and not hz:
                            hx = 0.14
                shapes.append((lay, (round(x - hx, 3), round(y - hy, 3), round(x + hx, 3), round(y + hy, 3)), net))
            shapes.append((kind, (round(x - 0.14, 3), round(y - 0.14, 3), round(x + 0.14, 3), round(y + 0.14, 3)), net))
    def lbridge(a, b, corner):
        (ax, ay), (bx, by) = a, b
        kx, ky = corner
        return [(round(min(ax, kx) - 0.14, 3), round(ky - 0.14, 3), round(max(ax, kx) + 0.14, 3), round(ky + 0.14, 3))
                if ay == ky else (round(kx - 0.14, 3), round(min(ay, ky) - 0.14, 3), round(kx + 0.14, 3), round(max(ay, ky) + 0.14, 3)),
                (round(min(bx, kx) - 0.14, 3), round(ky - 0.14, 3), round(max(bx, kx) + 0.14, 3), round(ky + 0.14, 3))
                if by == ky else (round(kx - 0.14, 3), round(min(by, ky) - 0.14, 3), round(kx + 0.14, 3), round(max(by, ky) + 0.14, 3))]
    def clear(lay, rects, net):
        for l2, r, n2 in shapes:
            if l2 == lay and n2 != net:
                for q in rects:
                    if r[0] < q[2] + 0.28 and q[0] < r[2] + 0.28 and r[1] < q[3] + 0.28 and q[1] < r[3] + 0.28:
                        return False
        return True
    for lo, hi, a, b, net in pend_bridge:
        for lay in (lo, hi):
            opts = [lbridge(a, b, (a[0], b[1])), lbridge(a, b, (b[0], a[1]))]
            pick = next((o for o in opts if clear(lay, o, net)), None)
            if pick is None:
                raise SystemExit(f"via bridge for {net} at {a} has no clear L on {lay}")
            shapes += [(lay, q, net) for q in pick]
    # terminal patches: grow each pin stub / TT pin / column stub to the bbox of the same-net route shapes that
    # land on it (removes the 0.01-0.1 um steps between an off-grid pin and an on-grid wire or via pad)
    cands = [(l, tuple(r), n) for l, r, n in R["_stubs"]]
    termrects = [(l, r, n) for n, grps in F.terms.items() for grp in grps for l, r in grp]
    for l, r, n in F.shapes:
        if l in ("metal2", "metal3") and any(tl == l and tn == n and r[0] <= tr[0] + 1e-6 and r[2] >= tr[2] - 1e-6
                                            and r[1] <= tr[1] + 1e-6 and r[3] >= tr[3] - 1e-6 for tl, tr, tn in termrects):
            cands.append((l, r, n))
    for pn, px in fp.PINS_TOP.items():
        cands.append(("metal4", (px - 0.3, 324.36, px + 0.3, 325.36), pn))
    routed = {}
    for l, r, n in shapes:
        routed.setdefault((l, n), []).append(r)
    # a patch reaches past both the stub and the wire it joins, into space the router never saw: keep it 0.28 um
    # (Euclidean) from every other net's shape on its layer, earlier patches included (2026-11-21: the cfg_out[29]
    # and [30] staircase-stub patches came 0.21 um apart corner to corner, M3.2a)
    bins = {}
    def bin_add(l, r, n):
        for gx in range(int(r[0] // 5), int(r[2] // 5) + 1):
            for gy in range(int(r[1] // 5), int(r[3] // 5) + 1):
                bins.setdefault((l, gx, gy), []).append((r, n))
    for l, r, n in shapes:
        if l in ("metal2", "metal3", "metal4"):
            bin_add(l, r, n)
    def clear28(l, B, n):
        for gx in range(int((B[0] - 0.28) // 5), int((B[2] + 0.28) // 5) + 1):
            for gy in range(int((B[1] - 0.28) // 5), int((B[3] + 0.28) // 5) + 1):
                for r, n2 in bins.get((l, gx, gy), ()):
                    if n2 != n:
                        dx = max(0.0, max(B[0], r[0]) - min(B[2], r[2])); dy = max(0.0, max(B[1], r[1]) - min(B[3], r[3]))
                        if dx * dx + dy * dy < 0.28 ** 2 - 1e-6:
                            return False
        return True
    npatch = nskip = 0
    for l, S, n in cands:
        hits = [r for r in routed.get((l, n), []) if r[0] < S[2] - 1e-6 and r[2] > S[0] + 1e-6
                and r[1] < S[3] - 1e-6 and r[3] > S[1] + 1e-6 and r != S]
        if not hits:
            continue
        for h in hits:
            ox0, ox1 = max(S[0], h[0]), min(S[2], h[2]); oy0, oy1 = max(S[1], h[1]), min(S[3], h[3])
            px = max(S[0] - h[0], h[2] - S[2], 0.0); py = max(S[1] - h[1], h[3] - S[3], 0.0)
            ux0, uy0 = min(S[0], h[0]), min(S[1], h[1]); ux1, uy1 = max(S[2], h[2]), max(S[3], h[3])
            Bs = []
            # the 0.3 um band is centred on the overlap but kept inside the stub's own extent where the wire runs on
            # past the stub end (2026-11-20: a band poking 0.08 um out of a fan-out stub end came 0.2 um from a
            # neighbour's jog, M2.2a)
            # band positions, preferred first; the first one clear of other nets is used
            def inside(c, a0, a1, w0, w1):
                lo, hi = c - 0.15, c + 0.15
                opts = []
                if w1 > a1 + 1e-6 and hi > a1 and a1 - 0.3 >= a0 - 1e-6:
                    opts.append((a1 - 0.3, a1))
                elif w0 < a0 - 1e-6 and lo < a0 and a0 + 0.3 <= a1 + 1e-6:
                    opts.append((a0, a0 + 0.3))
                return opts + [(lo, hi)]
            if 1e-6 < px <= 0.15 and (h[2] - h[0] <= 0.45 or h[3] - h[1] > h[2] - h[0]):
                Bs.append([[ux0, max(uy0, lo), ux1, min(uy1, hi)]
                           for lo, hi in inside((oy0 + oy1) / 2, S[1], S[3], h[1], h[3])])
            if 1e-6 < py <= 0.15 and (h[3] - h[1] <= 0.45 or h[2] - h[0] > h[3] - h[1]):
                Bs.append([[max(ux0, lo), uy0, min(ux1, hi), uy1]
                           for lo, hi in inside((ox0 + ox1) / 2, S[0], S[2], h[0], h[2])])
            for opts in Bs:
                ok = None
                for B in opts:            # stay in the outer part of the stub (away from the block edge)
                    if h[3] > S[3] + 1e-6 and h[1] >= S[1] - 1e-6: B[1] = max(B[1], S[3] - 0.3)
                    if h[1] < S[1] - 1e-6 and h[3] <= S[3] + 1e-6: B[3] = min(B[3], S[1] + 0.3)
                    if h[2] > S[2] + 1e-6 and h[0] >= S[0] - 1e-6: B[0] = max(B[0], S[2] - 0.3)
                    if h[0] < S[0] - 1e-6 and h[2] <= S[2] + 1e-6: B[2] = min(B[2], S[0] + 0.3)
                    B = tuple(round(v, 3) for v in B)
                    if B[2] - B[0] >= 0.28 and B[3] - B[1] >= 0.28 and clear28(l, B, n):
                        ok = B
                        break
                if ok is None:
                    if any(B[2] - B[0] >= 0.28 and B[3] - B[1] >= 0.28 for B in opts):
                        nskip += 1
                        print("terminal patch skipped (no position 0.28 um clear of other nets):", l, n, S)
                    continue
                shapes.append((l, ok, n)); bin_add(l, ok, n); npatch += 1
    print("terminal patches:", npatch, "skipped:", nskip, "dropped vias:", ndrop)
    # same-net notch fill: close every net's metal by 0.15 um (KLayout), paint the added area
    try:
        import klayout.db as kdb
        groups, extra = {}, {}
        for l, r, n in shapes:
            if l in ("metal2", "metal3", "metal4"):
                groups.setdefault((l, n), []).append(r)
        conn = {}
        for nn, lst in C.nets().items():
            for inst, pin in lst:
                conn[(inst, pin)] = nn
        stubs_by = {}
        for l, r, n in R["_stubs"]:
            stubs_by.setdefault((l, n), []).append(r)
        for inst, (cell, x, y) in I.items():
            for pin, plist in GM.geo(cell)["pins"].items():
                n = conn.get((inst, pin))
                for p in plist:
                    sts = stubs_by.get((p["layer"], n), [])
                    for q in p["rects"]:
                        q = (q[0] + x, q[1] + y, q[2] + x, q[3] + y)
                        if any(q[0] < t[2] + 0.5 and q[2] > t[0] - 0.5 and q[1] < t[3] + 0.5 and q[3] > t[1] - 0.5 for t in sts):
                            extra.setdefault((p["layer"], n), []).append(q)
        nfill = 0
        layer_all, placed = {}, {}
        for (l, n), rs in groups.items():
            reg = kdb.Region()
            for r in rs:
                reg.insert(kdb.Box(*[int(round(v * 1000)) for v in r]))
            layer_all.setdefault(l, []).append((n, reg.merged()))
        for (l, n), rs in groups.items():
            reg = kdb.Region()
            for r in rs:
                reg.insert(kdb.Box(*[int(round(v * 1000)) for v in r]))
            for r in extra.get((l, n), []):
                reg.insert(kdb.Box(*[int(round(v * 1000)) for v in r]))
            reg.merge()
            fill = reg.sized(150).sized(-150) - reg
            if not fill.is_empty():         # never bring a fill closer than 0.28 um to another net (or its fills)
                others = kdb.Region()
                for nn, rr in layer_all[l] + placed.get(l, []):
                    if nn != n:
                        others += rr
                fill = fill - others.sized(280)
                placed.setdefault(l, []).append((n, fill.dup()))
            for poly in fill.each():
                for t in poly.decompose_trapezoids():
                    b = t.bbox()
                    shapes.append((l, (b.left / 1000, b.bottom / 1000, b.right / 1000, b.top / 1000), n)); nfill += 1
        print("notch fills:", nfill)
    except ImportError:
        print("klayout not available: no notch fill")
    order = ["metal1", "metal2", "metal3", "metal4", "via1", "via2", "via3"]
    seen = set()
    for lay in order:
        for l, r, n in shapes:
            if l == lay and (l, r) not in seen:
                seen.add((l, r))
                T.append(f"box values {r[0]:.3f}um {r[1]:.3f}um {r[2]:.3f}um {r[3]:.3f}um; paint {l}")
    T += ["select top cell", f"cd {root}/mag", f"save {C.TOP}", f"cd {C.WORK}",
          f"gds write {root}/gds/{C.TOP}.gds",
          f"lef write {root}/lef/{C.TOP}.lef -hide -pinonly",
          f"file mkdir {C.WORK}/ext", f"extract path {C.WORK}/ext", "extract all", "ext2spice lvs",
          f"ext2spice -p {C.WORK}/ext -o {C.WORK}/top_ext.spice", "quit -noprompt"]
    (C.WORK / "assemble.tcl").write_text("\n".join(T) + "\n")
    print("wrote", C.WORK / "assemble.tcl", len(T), "lines")
    return shapes


if __name__ == "__main__":
    main()
